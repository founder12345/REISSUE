import { expect,test } from '@playwright/test';
import { Pool } from 'pg';
import { action,mailLink,origin,password,register,username } from './helpers';

test('verified email, profile persistence, recovery and single-use credentials',async({page})=>{
  const email='identity-'+Date.now().toString(36)+'@example.test';
  const user=username(email);
  expect(await action(page.request,{action:'register',email,name:'Identity tester',username:user,password,terms:'yes',termsVersion:'internal-draft-1'})).toContain('purpose=verify');
  expect(await action(page.request,{action:'sign-in',email,password})).toContain('Verify your email');
  expect((await page.request.get('/account/export')).status()).toBe(401);
  const verification=await mailLink(email);
  await page.goto(verification.href);
  await page.getByLabel('Your registration password').fill(password);
  await page.getByRole('button',{name:'Verify email'}).click();
  await expect(page.getByRole('heading',{name:'Identity tester'})).toBeVisible();
  await page.getByLabel('Display name').fill('Updated archive member');
  await page.getByRole('button',{name:'Save settings'}).click();
  await expect(page.getByRole('heading',{name:'Updated archive member'})).toBeVisible();
  await page.getByRole('button',{name:'Sign out'}).click();
  const token=verification.searchParams.get('token')??'';
  expect(await action(page.request,{action:'verify-email',token,password})).toContain('could not be verified');
  expect(await action(page.request,{action:'sign-in',email,password})).toBe(origin+'/account');
  await page.goto('/account');
  await expect(page.getByRole('heading',{name:'Updated archive member'})).toBeVisible();
  await action(page.request,{action:'forgot-password',email});
  const recovery=await mailLink(email,'reset');
  const newPassword='Recovery-password-registered!';
  expect(await action(page.request,{action:'reset-password',token:recovery.searchParams.get('token')??'',password:newPassword})).toContain('Password reset.');
  expect((await page.request.get('/account/export')).status()).toBe(401);
  expect(await action(page.request,{action:'sign-in',email,password})).toContain('did not match');
  expect(await action(page.request,{action:'sign-in',email,password:newPassword})).toBe(origin+'/account');
});
test('privacy export and right to erase are bound to the signed-in user',async({browser,request})=>{
  const one=await browser.newContext(), two=await browser.newContext();
  const stamp=Date.now().toString(36), email='rights-'+stamp+'@example.test';
  await register(one.request,email,'Portability tester');
  await register(two.request,'other-'+stamp+'@example.test','Second private account');
  expect(await action(one.request,{action:'rights-file',kind:'restriction',body:'Please review the processing of my old campaign contribution.',returnTo:'/rights'})).toContain('Request received');
  const file=await one.request.get('/account/export');
  expect(file.status()).toBe(200);
  expect(file.headers()['content-disposition']).toContain('reissue-account-data.json');
  const data=await file.json();
  expect(data.profile[0].email).toBe(email);
  expect(data.profile[0]).not.toHaveProperty('password_hash');
  expect(data.terms[0].version).toBe('internal-draft-1');
  expect(data.rights[0].kind).toBe('restriction');
  const other=await two.request.get('/account/export?userId='+encodeURIComponent(email));
  expect((await other.json()).rights).toEqual([]);
  expect((await request.get('/account/export')).status()).toBe(401);
  await action(one.request,{action:'delete-account',password});
  expect((await one.request.get('/account/export')).status()).toBe(401);
  expect(await action(one.request,{action:'sign-in',email,password})).toContain('did not match');
  await one.close();await two.close();
});
test('optional analytics follow consent and withdrawal',async({page})=>{
  const pool=new Pool({connectionString:process.env.DATABASE_URL});
  const token=Date.now().toString(36);
  const target=new URL('/explore?q=consent-'+token,origin).href;
  const thirdParty:string[]=[];
  page.on('request',request=>{
    const url=new URL(request.url());
    if(['http:','https:'].includes(url.protocol)&&url.origin!==origin)thirdParty.push(url.origin);
  });
  try{
    await page.goto('/');
    await page.getByRole('button',{name:'Reject all'}).click();
    await page.goto(target);
    await expect(page.getByRole('heading',{name:/products for/})).toBeVisible();
    const rows=async()=>Number((await pool.query('SELECT count(*) FROM search_events WHERE query=$1',['consent-'+token])).rows[0].count);
    expect(await rows()).toBe(0);
    const initial=await page.context().cookies();
    expect(initial.find(c=>c.name==='reissue_consent')?.value).toBe('1.necessary');
    await page.goto('/cookies');
    await page.getByRole('checkbox',{name:'Allow optional archive analytics'}).check();
    await page.getByRole('button',{name:'Save cookie preferences'}).click();
    await expect(page.getByRole('button',{name:'Withdraw analytics consent'})).toBeVisible();
    await page.goto(target);
    await expect(page.getByRole('heading',{name:/products for/})).toBeVisible();
    expect(await rows()).toBe(1);
    await page.goto('/cookies');
    await page.getByRole('button',{name:'Withdraw analytics consent'}).click();
    await expect(page.getByRole('checkbox',{name:'Allow optional archive analytics'})).not.toBeChecked();
    await page.goto(target);
    await expect(page.getByRole('heading',{name:/products for/})).toBeVisible();
    expect(await rows()).toBe(1);
    expect(thirdParty).toEqual([]);
  }finally{await pool.end();}
});
test('Google routes fail closed when the provider or flow is unavailable',async({request})=>{
  const start=await request.get('/api/auth/google',{maxRedirects:0});
  expect(start.status()).toBe(303);
  expect(start.headers().location).toContain('/account?error=');
  const callback=await request.get('/api/auth/google/callback?code=unrelated&state=unrelated',{maxRedirects:0});
  expect(callback.status()).toBe(303);
  expect(callback.headers().location).toContain('/account?error=');
});

