test('content reports reach an administrator and private cases publish a response to the requester',async({page,browser,request})=>{
  const stamp=Date.now().toString(36);
  const statement='A rights holder asked us to review this catalogue image '+stamp;
  await page.goto('/report-content');
  await page.getByLabel('Content URL').fill(origin+'/products/walkman-tps-l2');
  await page.getByLabel('Contact email').fill('report-'+stamp+'@example.test');
  await page.getByLabel('Reason and supporting information').fill(statement);
  await page.getByRole('checkbox',{name:/I believe/}).check();
  await page.getByRole('button',{name:'Send report'}).click();
  await expect(page.getByText('Report received.')).toBeVisible();
  expect((await request.get('/admin')).status()).toBe(404);

  const member=await browser.newContext();
  await register(member.request,'case-'+stamp+'@example.test','Case owner');
  const requestText='Please review a correction to my personal information '+stamp;
  expect(await action(member.request,{action:'rights-file',kind:'rectification',body:requestText})).toContain('Request received');
  const mod=await browser.newContext();
  await action(mod.request,{action:'sign-in',email:process.env.TEST_ADMIN_EMAIL??'',password:process.env.TEST_ADMIN_PASSWORD??''});
  const review=await mod.newPage();
  await review.goto('/admin');
  const report=review.locator('details').filter({hasText:statement});
  await expect(report).toHaveCount(1);
  const privacy=review.locator('details').filter({hasText:requestText});
  await privacy.locator('summary').click();
  await privacy.getByLabel('Status').selectOption('closed');
  await privacy.getByLabel('Response').fill('The correction request has been reviewed.');
  await privacy.getByRole('button',{name:'Update case'}).click();
  await expect(privacy).toHaveCount(0);
  const memberPage=await member.newPage();
  await memberPage.goto('/rights');
  await expect(memberPage.getByText('Response · The correction request has been reviewed.')).toBeVisible();
  await member.close();
  await mod.close();
});
